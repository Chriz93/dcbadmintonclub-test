import {readFileSync,writeFileSync} from 'node:fs';
const dir=new URL('../migrations/',import.meta.url),names=['L22_integrity.sql','L23_recovery.sql','L24_season_operations.sql'];
const bodies=names.map(name=>{
 const sql=readFileSync(new URL(name,dir),'utf8');
 if(!/^begin;$/m.test(sql)||!sql.trimEnd().endsWith('commit;'))throw Error('Migration transaction wrapper changed: '+name);
 return '-- '+name+'\n'+sql.replace(/^begin;\n/m,'').replace(/commit;\s*$/,'').trimEnd();
});
const sql='-- Generated by legacy/scripts/build-audit-migration.mjs. Apply only to TEST.\n-- L22–L24 are one transaction: any failure rolls the entire upgrade back.\nbegin;\n'+bodies.join('\n\n')+'\ncommit;\n';
const file=new URL('TEST_2026-09-13.sql',dir);
if(process.argv.includes('--check')){if(readFileSync(file,'utf8')!==sql)throw Error('Regenerate TEST_2026-09-13.sql');}
else writeFileSync(file,sql);
console.log('Combined TEST migration '+(process.argv.includes('--check')?'verified':'generated')+'.');
