// Builds the two 10 October migration bundles from L31 — one for TEST, one for production — so each is a single
// paste into the Supabase SQL editor, in one transaction, that REFUSES to run against the wrong project.
// The October 6 bundles are already applied to both databases and are frozen; this release gets its own pair.
//   node legacy/scripts/build-vote-link-migration.mjs          → writes both bundles
//   node legacy/scripts/build-vote-link-migration.mjs --check  → fails if either is out of date (CI runs this)
import { readFileSync, writeFileSync } from "node:fs";
const dir = new URL("../migrations/", import.meta.url);
const names = ["L31_vote_from_the_email.sql"];
const bodies = names.map((name) => {
  const sql = readFileSync(new URL(name, dir), "utf8");
  if (!/^begin;$/m.test(sql) || !sql.trimEnd().endsWith("commit;")) throw Error("Migration transaction wrapper changed: " + name);
  return "-- ═══════════ " + name + " ═══════════\n" + sql.replace(/^begin;\n/m, "").replace(/commit;\s*$/, "").trimEnd();
});
const GUARD = {
  test: `-- This bundle is for the TEST project (wgolevihkvmosajumzvl) and refuses to run anywhere else.
select public.assert_test_environment();`,
  production: `-- This bundle is for the PRODUCTION project (bwepvxelvwgwxrnaglrx) and refuses to run anywhere else.
do $$ begin
 if exists(select 1 from public.environment where name='test') then raise exception 'Refusing: this database is marked test'; end if;
 if not exists(select 1 from public.environment where name='production') then raise exception 'Refusing: this database is not marked production'; end if;
end $$;`,
};
const HEAD = (env) => `-- Maplewood league migration, 10 October 2026 — ${env.toUpperCase()}.
-- Generated by legacy/scripts/build-vote-link-migration.mjs. Paste the whole file into the SQL editor of the
-- ${env.toUpperCase()} project and run it in one go; it is one transaction, so any failure rolls the whole thing back.
-- Afterwards run legacy/migrations/verify.sql: every row must read OK.
--
-- L31  answering a vote reminder from the email, without signing in. Adds vote_links (one 256-bit token per player
--      per session, dead at the voting deadline) and three service-role functions the confirm page uses. The rules a
--      vote must pass move out of set_rsvp into rsvp_write so the emailed path and the app path cannot drift apart;
--      set_rsvp allows exactly what it allowed before.
--
--      NOTE: a link in an inbox is not proof of identity. Anyone who can read a player's email, or who is forwarded
--      it, can answer as that player. That is the cost of not signing in. It is bounded to one player, one session,
--      an answer they can change, expiring at the deadline, and every use counted.
--
-- No player, score, payment or waiver record is read or written: one new table, one new function, four replaced.
`;
let changed = 0;
for (const [env, file] of [["test", "TEST_2026-10-10.sql"], ["production", "PROD_2026-10-10.sql"]]) {
  const sql = HEAD(env) + "begin;\n" + GUARD[env] + "\n\n" + bodies.join("\n\n") + "\ncommit;\n";
  const path = new URL(file, dir);
  if (process.argv.includes("--check")) {
    let have = ""; try { have = readFileSync(path, "utf8"); } catch { /* missing */ }
    if (have !== sql) throw Error("Regenerate " + file + " (node legacy/scripts/build-vote-link-migration.mjs)");
  } else { writeFileSync(path, sql); changed++; }
}
console.log("Vote-link migration bundles " + (process.argv.includes("--check") ? "verified" : `generated (${changed})`) + ".");
