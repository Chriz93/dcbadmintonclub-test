// Builds the two 19 October migration bundles from L32 — one for TEST, one for production — so each is a single
// paste into the Supabase SQL editor, in one transaction, that REFUSES to run against the wrong project.
// The October 6 and October 10 bundles are frozen; this release gets its own pair.
//
// ORDER MATTERS. L32 replaces set_rsvp and issue_vote_link, both of which L31 defines, so the 10 October bundle has
// to be applied first. The migration says so itself and aborts if it is not, rather than leaving half a release.
//   node legacy/scripts/build-spare-seat-migration.mjs          → writes both bundles
//   node legacy/scripts/build-spare-seat-migration.mjs --check  → fails if either is out of date (CI runs this)
import { readFileSync, writeFileSync } from "node:fs";
const dir = new URL("../migrations/", import.meta.url);
const names = ["L32_a_spare_seat_is_the_organizers_to_give.sql"];
const bodies = names.map((name) => {
  const sql = readFileSync(new URL(name, dir), "utf8");
  if (!/^begin;$/m.test(sql) || !sql.trimEnd().endsWith("commit;")) throw Error("Migration transaction wrapper changed: " + name);
  return "-- ═══════════ " + name + " ═══════════\n" + sql.replace(/^begin;\n/m, "").replace(/commit;\s*$/, "").trimEnd();
});
const GUARD = {
  test: `-- This bundle is for the TEST project (wgolevihkvmosajumzvl) and refuses to run anywhere else.
select public.assert_test_environment();`,
  production: `-- This bundle is for the PRODUCTION project (bwepvxelvwgwxrnaglrx) and refuses to run anywhere else.
do $$ begin
 if exists(select 1 from public.environment where name='test') then raise exception 'Refusing: this database is marked test'; end if;
 if not exists(select 1 from public.environment where name='production') then raise exception 'Refusing: this database is not marked production'; end if;
end $$;`,
};
const HEAD = (env) => `-- Maplewood league migration, 19 October 2026 — ${env.toUpperCase()}.
-- Generated by legacy/scripts/build-spare-seat-migration.mjs. Paste the whole file into the SQL editor of the
-- ${env.toUpperCase()} project and run it in one go; it is one transaction, so any failure rolls the whole thing back.
-- Afterwards run legacy/migrations/verify.sql: every row must read OK.
--
-- APPLY THE 10 OCTOBER BUNDLE FIRST. L32 replaces two functions L31 defines; it checks for them and aborts if they
-- are missing, so running this on a database without L31 changes nothing.
--
-- L32  a spare does not answer for themselves. The organizer: "Spares should not be able to vote, Spares are only
--      voted by admin manually." A spare used to claim an open seat by answering 'coming', and the seats went to
--      whoever replied first. Now the seat is given with Call In, which writes the very same rsvps row, so the
--      reservation, the payment check, the seat emails and the line-up are all untouched.
--
--      Three doors are closed, not one: set_rsvp refuses a spare answering for themselves, issue_vote_link refuses
--      to mint a one-tap token for a spare, and reminder_targets stops offering open seats to spares at all.
--
-- No row is deleted and no answer already given is changed: a spare who was already down as coming stays exactly as
-- they are. No player, score, payment or waiver record is read or written: three functions replaced.
`;
let changed = 0;
for (const [env, file] of [["test", "TEST_2026-10-19.sql"], ["production", "PROD_2026-10-19.sql"]]) {
  const sql = HEAD(env) + "begin;\n" + GUARD[env] + "\n\n" + bodies.join("\n\n") + "\ncommit;\n";
  const path = new URL(file, dir);
  if (process.argv.includes("--check")) {
    let have = ""; try { have = readFileSync(path, "utf8"); } catch { /* missing */ }
    if (have !== sql) throw Error("Regenerate " + file + " (node legacy/scripts/build-spare-seat-migration.mjs)");
  } else { writeFileSync(path, sql); changed++; }
}
console.log("Spare-seat migration bundles " + (process.argv.includes("--check") ? "verified" : `generated (${changed})`) + ".");
