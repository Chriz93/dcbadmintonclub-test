// Builds the two October migration bundles from L28, L29 and L30 — one for TEST, one for production — so each is a
// single paste into the Supabase SQL editor, in one transaction, that REFUSES to run against the wrong project.
// That guard is the whole point: on 23 September an L27 paste nearly went into production because the editor tab had
// silently changed project. A bundle that checks public.environment before it touches anything cannot do that.
//   node legacy/scripts/build-october-migration.mjs            → writes both bundles
//   node legacy/scripts/build-october-migration.mjs --check    → fails if either is out of date (CI runs this)
import { readFileSync, writeFileSync } from "node:fs";
const dir = new URL("../migrations/", import.meta.url);
const names = ["L28_organizer_keys_in_undo_and_rollover.sql", "L29_regular_capacity.sql", "L30_spare_seats_match_the_app.sql"];
const bodies = names.map((name) => {
  const sql = readFileSync(new URL(name, dir), "utf8");
  if (!/^begin;$/m.test(sql) || !sql.trimEnd().endsWith("commit;")) throw Error("Migration transaction wrapper changed: " + name);
  return "-- ═══════════ " + name + " ═══════════\n" + sql.replace(/^begin;\n/m, "").replace(/commit;\s*$/, "").trimEnd();
});
const GUARD = {
  test: `-- This bundle is for the TEST project (wgolevihkvmosajumzvl) and refuses to run anywhere else.
select public.assert_test_environment();`,
  production: `-- This bundle is for the PRODUCTION project (bwepvxelvwgwxrnaglrx) and refuses to run anywhere else.
do $$ begin
 if exists(select 1 from public.environment where name='test') then raise exception 'Refusing: this database is marked test'; end if;
 if not exists(select 1 from public.environment where name='production') then raise exception 'Refusing: this database is not marked production'; end if;
end $$;`,
};
const HEAD = (env) => `-- Maplewood league migration, 6 October 2026 — ${env.toUpperCase()}.
-- Generated by legacy/scripts/build-october-migration.mjs. Paste the whole file into the SQL editor of the ${env.toUpperCase()}
-- project and run it in one go; it is one transaction, so any failure rolls all three migrations back together.
-- Afterwards run legacy/migrations/verify.sql: every row must read OK.
--
-- L28  the organizer's hand-made court moves and a drop-in's starting points are part of Undo, and are cleared at
--      season rollover. Without it, Undo put a court back and left the adjustment behind.
-- L29  set_regular_capacity: the organizer can change how many regular places the season has (2 to 30, never below the
--      regulars already approved, written to audit_log). Without it the app can ask to go over the cap and the database
--      refuses, which is worse than not asking.
-- L30  one rule for the spare seats. spare_seat_status and reminder_targets each kept their own copy (one seat per
--      decline); on the 4 October data the app, spare_seat_status and reminder_targets gave 4, 2 and 2 for one night.
--      NOTE: more spares can hold a reserved seat than before, so the reminder worker can send more "your seat is
--      reserved" messages. That is the fix working, and it is a change in what players receive.
--
-- No player, score, payment or waiver record is read or written by any of this: it replaces four function bodies and
-- adds one.
`;
let changed = 0;
for (const [env, file] of [["test", "TEST_2026-10-06.sql"], ["production", "PROD_2026-10-06.sql"]]) {
  const sql = HEAD(env) + "begin;\n" + GUARD[env] + "\n\n" + bodies.join("\n\n") + "\ncommit;\n";
  const path = new URL(file, dir);
  if (process.argv.includes("--check")) {
    let have = ""; try { have = readFileSync(path, "utf8"); } catch { /* missing */ }
    if (have !== sql) throw Error("Regenerate " + file + " (node legacy/scripts/build-october-migration.mjs)");
  } else { writeFileSync(path, sql); changed++; }
}
console.log("October migration bundles " + (process.argv.includes("--check") ? "verified" : `generated (${changed})`) + ".");
